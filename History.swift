import AppKit
import UniformTypeIdentifiers
import os.log

struct Clip: Codable, Equatable {
    struct Item: Codable, Equatable {
        let representations: [String: Data]

        var hasImage: Bool {
            representations.keys.contains { UTType($0)?.conforms(to: .image) == true }
        }

        var plainText: String? {
            // Images and file copies retain their original representations.
            guard !hasImage,
                  representations[NSPasteboard.PasteboardType.fileURL.rawValue] == nil else { return nil }
            if let data = representations[NSPasteboard.PasteboardType.string.rawValue],
               let text = String(data: data, encoding: .utf8) {
                return text
            }
            for (type, format) in [
                (NSPasteboard.PasteboardType.rtf, NSAttributedString.DocumentType.rtf),
                (.rtfd, .rtfd),
                (.html, .html)
            ] {
                if let data = representations[type.rawValue],
                   let text = try? NSAttributedString(
                       data: data, options: [.documentType: format], documentAttributes: nil
                   ) {
                    return text.string
                }
            }
            return representations[NSPasteboard.PasteboardType.URL.rawValue]
                .flatMap { String(data: $0, encoding: .utf8) }
        }
    }

    let items: [Item]
    let title: String
    let byteCount: Int

    private static let supportedTypes: [NSPasteboard.PasteboardType] = [
        .string, .rtf, .rtfd, .html, .pdf, .png, .tiff, .fileURL, .URL
    ]
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ]
    static let byteLimit = 20 * 1024 * 1024

    init(image: Data, type: UTType) {
        items = [Item(representations: [type.identifier: image])]
        title = "Image"
        byteCount = image.count
    }

    var isEmptyRichText: Bool {
        guard items.count == 1 else { return false }
        let types = Set(items[0].representations.keys)
        return types.contains(NSPasteboard.PasteboardType.rtf.rawValue)
            && types.isSubset(of: [NSPasteboard.PasteboardType.rtf.rawValue, NSPasteboard.PasteboardType.string.rawValue])
            && items[0].plainText == ""
    }

    init?(pasteboard: NSPasteboard) {
        guard let source = pasteboard.pasteboardItems, !source.isEmpty,
              !source.contains(where: { item in
                  item.types.contains { Self.ignoredTypes.contains($0.rawValue) }
              }) else { return nil }

        var captured: [Item] = []
        var size = 0
        var preview: String?
        var fileCount = 0
        var hasImage = false

        for item in source {
            var representations: [String: Data] = [:]
            for type in item.types where Self.supportedTypes.contains(type)
                || UTType(type.rawValue)?.conforms(to: .image) == true {
                guard let data = item.data(forType: type), !data.isEmpty else { continue }
                guard data.count <= Self.byteLimit - size else { return nil }
                representations[type.rawValue] = data
                size += data.count
            }
            guard !representations.isEmpty else { continue }
            if let file = item.string(forType: .fileURL) {
                fileCount += 1
                preview = preview ?? URL(string: file)?.lastPathComponent
            } else {
                preview = preview ?? item.string(forType: .string) ?? item.string(forType: .URL)
            }
            hasImage = hasImage || Item(representations: representations).hasImage
            captured.append(Item(representations: representations))
        }

        guard !captured.isEmpty else { return nil }
        items = captured
        byteCount = size
        let line = preview?.split(whereSeparator: \.isWhitespace).prefix(64).joined(separator: " ")
        let label = fileCount > 1 ? "\(fileCount) files" : line.flatMap { $0.isEmpty ? nil : $0 }
        let display = hasImage && fileCount == 0 ? "Image" : (label ?? "Document")
        let excerpt = display.prefix(68)
        title = excerpt.endIndex == display.endIndex ? display : String(excerpt) + "…"
    }

    func write(to pasteboard: NSPasteboard) -> Bool {
        let objects = items.map { item -> NSPasteboardItem in
            let object = NSPasteboardItem()
            if item.hasImage && item.representations[NSPasteboard.PasteboardType.fileURL.rawValue] == nil {
                for (type, data) in item.representations where UTType(type)?.conforms(to: .image) == true {
                    object.setData(data, forType: NSPasteboard.PasteboardType(type))
                }
            } else if let text = item.plainText {
                object.setString(text, forType: .string)
            } else {
                for (type, data) in item.representations {
                    object.setData(data, forType: NSPasteboard.PasteboardType(type))
                }
            }
            return object
        }
        pasteboard.clearContents()
        return pasteboard.writeObjects(objects)
    }
}

final class History {
    private(set) var clips: [Clip]
    private let file: URL
    private let saves = DispatchQueue(label: "local.copyshelf.history", qos: .utility)

    init(file: URL) {
        self.file = file
        if let bytes = try? Data(contentsOf: file),
           let saved = try? PropertyListDecoder().decode([Clip].self, from: bytes) {
            clips = saved
        } else {
            clips = []
        }
    }

    func record(_ clip: Clip) {
        if clips.first?.items == clip.items { return }
        clips.removeAll { $0.items == clip.items }
        clips.insert(clip, at: 0)
        var size = 0
        clips = Array(clips.prefix(100).prefix { entry in
            size += entry.byteCount
            return size <= 64 * 1024 * 1024
        })
        save()
    }

    func clear() {
        clips.removeAll()
        save()
    }

    func finishSaving() {
        saves.sync {}
    }

    private func save() {
        let snapshot = clips
        let file = file
        saves.async {
            do {
                try FileManager.default.createDirectory(
                    at: file.deletingLastPathComponent(),
                    withIntermediateDirectories: true,
                    attributes: [.posixPermissions: 0o700]
                )
                let encoder = PropertyListEncoder()
                encoder.outputFormat = .binary
                try encoder.encode(snapshot).write(to: file, options: .atomic)
            } catch {
                os_log("Could not save clipboard history: %{public}@", error.localizedDescription)
            }
        }
    }
}

final class ClipboardMonitor {
    private let pasteboard: NSPasteboard
    private var changeCount: Int
    let history: History
    private let recoverImage: () -> Clip?

    init(pasteboard: NSPasteboard, history: History, recoverImage: @escaping () -> Clip? = { nil }) {
        self.recoverImage = recoverImage
        self.pasteboard = pasteboard
        self.history = history
        changeCount = pasteboard.changeCount
    }

    func captureIfChanged() {
        let current = pasteboard.changeCount
        guard current != changeCount else { return }
        let clip = Clip(pasteboard: pasteboard)
        let image = clip?.isEmptyRichText == true ? recoverImage() : nil
        // Finder selection and file reads may take long enough for a newer copy to arrive.
        guard pasteboard.changeCount == current else { return }
        changeCount = current
        if let image {
            if image.write(to: pasteboard) { changeCount = pasteboard.changeCount }
            history.record(image)
        } else if let clip {
            history.record(clip)
        }
    }

    func restore(_ clip: Clip) -> Bool {
        captureIfChanged()
        let written = clip.write(to: pasteboard)
        changeCount = pasteboard.changeCount
        if written { history.record(clip) }
        return written
    }
}
